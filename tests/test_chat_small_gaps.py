"""Protocol-type generation and the SearXNG status reader's Docker and HTTP edges, mocked."""

import io
import json
import subprocess

import pytest

from dreamference.chat import desktop_protocol_types as dpt
from dreamference.chat import searxng_status as status_module
from dreamference.chat.desktop_protocol_types import DesktopProtocolTypes
from dreamference.chat.searxng_status import SearxngStatus


def fake_zstd(files):
    def run(argv, **kwargs):
        assert argv[0] == "zstd"
        return subprocess.CompletedProcess(
            argv, 0, stdout=json.dumps({"typescript": files}).encode()
        )

    return run


def test_has_source_needs_the_export_and_zstd(tmp_path, monkeypatch):
    export = tmp_path / "e.zst"
    monkeypatch.setattr(dpt, "EXPERIMENTAL_EXPORTS", export)
    monkeypatch.setattr(dpt.shutil, "which", lambda name: "/usr/bin/zstd")
    assert DesktopProtocolTypes.has_source() is False
    export.write_bytes(b"x")
    assert DesktopProtocolTypes.has_source() is True
    monkeypatch.setattr(dpt.shutil, "which", lambda name: None)
    assert DesktopProtocolTypes.has_source() is False


def test_exports_trims_trailing_spaces_and_tabs_before_newlines(monkeypatch):
    monkeypatch.setattr(dpt.subprocess, "run", fake_zstd({"a.ts": "x  \ny\t\n  z \t", "b.ts": ""}))
    assert DesktopProtocolTypes.exports() == {"a.ts": "x\ny\n  z", "b.ts": ""}


def test_write_replaces_the_folder_and_counts_files(tmp_path, monkeypatch):
    monkeypatch.setattr(dpt.subprocess, "run", fake_zstd({"a.ts": "A \n", "sub/b.ts": "B"}))
    out = tmp_path / "protocol"
    (out / "old").mkdir(parents=True)
    (out / "old" / "stale.ts").write_text("stale")
    assert DesktopProtocolTypes.write(out) == 2
    assert not (out / "old").exists()
    assert (out / "a.ts").read_bytes() == b"A\n"
    assert (out / "sub" / "b.ts").read_text() == "B"


def test_drift_names_missing_extra_and_different_files(tmp_path, monkeypatch):
    monkeypatch.setattr(dpt.subprocess, "run", fake_zstd({"a.ts": "A", "b.ts": "B", "c.ts": "C"}))
    (tmp_path / "a.ts").write_text("A")
    (tmp_path / "b.ts").write_text("changed")
    (tmp_path / "extra.ts").write_text("E")
    assert DesktopProtocolTypes.drift(tmp_path) == [
        "missing: c.ts",
        "not generated by the pinned Codex: extra.ts",
        "differs: b.ts",
    ]
    (tmp_path / "b.ts").write_text("B")
    (tmp_path / "c.ts").write_text("C")
    (tmp_path / "extra.ts").unlink()
    assert DesktopProtocolTypes.drift(tmp_path) == []


class Reply(io.BytesIO):
    def __enter__(self):
        return self

    def __exit__(self, *exc):
        return False


def test_enabled_engines_keeps_general_web_engines_and_named_ones(monkeypatch):
    config = {
        "engines": [
            {"name": "web1", "enabled": True, "categories": ["general", "web"]},
            {"name": "web2", "categories": ["general", "web"]},
            {"name": "images", "enabled": True, "categories": ["images"]},
            {"name": status_module.GENERAL_ENGINES[0], "enabled": True},
        ]
    }
    seen = []

    def opener(url, timeout):
        seen.append(url)
        return Reply(json.dumps(config).encode())

    monkeypatch.setattr(status_module.urllib.request, "urlopen", opener)
    result = SearxngStatus.enabled_engines("http://h:1/")
    assert result == {"web1": True, "web2": False, status_module.GENERAL_ENGINES[0]: True}
    assert seen == ["http://h:1/config"]


@pytest.mark.parametrize("failure", [OSError("down"), ValueError("bad json")])
def test_enabled_engines_is_none_when_searxng_does_not_answer(monkeypatch, failure):
    def opener(url, timeout):
        raise failure

    monkeypatch.setattr(status_module.urllib.request, "urlopen", opener)
    assert SearxngStatus.enabled_engines("http://h") is None


def docker(inspect_code, inspect_out, logs=("out\nline\n", "err\n")):
    calls = []

    def run(argv, **kwargs):
        calls.append(argv)
        if argv[1] == "inspect":
            return subprocess.CompletedProcess(argv, inspect_code, stdout=inspect_out, stderr="")
        return subprocess.CompletedProcess(argv, 0, stdout=logs[0], stderr=logs[1])

    return run, calls


def test_container_log_reads_since_the_start_and_joins_both_streams(monkeypatch):
    run, calls = docker(0, "true 2020-11-01T00:00:00Z")
    monkeypatch.setattr(status_module.subprocess, "run", run)
    assert SearxngStatus.container_log("sx") == ["out", "line", "err"]
    assert calls[1][-3:] == ["--since", "2020-11-01T00:00:00Z", "sx"]


@pytest.mark.parametrize(
    ("code", "out"),
    [(1, ""), (0, "true"), (0, "false 2020-11-01T00:00:00Z"), (0, "true a b")],
)
def test_container_log_is_none_without_a_running_container(monkeypatch, code, out):
    run, calls = docker(code, out)
    monkeypatch.setattr(status_module.subprocess, "run", run)
    assert SearxngStatus.container_log("sx") is None
    assert len(calls) == 1
